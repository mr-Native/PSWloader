/* Archpx64EnableInterruptsAsm: 10-byte NOP, then fb c3 (sti; ret). Literal, unique in both builds. */
static const uint8_t k_sti[12] = {0x66,0x66,0x0f,0x1f,0x84,0x00,0x00,0x00,0x00,0x00,0xfb,0xc3};
#define STI_FB_OFF 10u

static int match_site(const uint8_t *t, size_t len, size_t at, const struct wl_sig *s)
{
    if (at < s->pre_len) return 0;
    for (uint8_t i = 0; i < s->pre_len; i++) if (t[at - s->pre_len + i] != s->pre[i]) return 0;
    if (at + 5 + s->suf_len > len) return 0;
    if (t[at] != 0xe8) return 0;
    for (uint8_t i = 0; i < s->suf_len; i++) if (t[at + 5 + i] != s->suf[i]) return 0;
    return 1;
}

int ps5_wl_locate(const uint8_t *t, size_t len, uint32_t text_rva, struct ps5_wl_loc *o)
{
    int i, rc = 0;
    for (i = 0; i < PS5_WL_SITES; i++) o->site_rva[i] = 0;
    o->sti_rva = 0; o->sti_ok = 0; o->sites_ok = 0;
    /* sti: unique literal */
    { size_t hit = 0, n = 0;
      for (size_t p = 0; p + sizeof(k_sti) <= len; p++) {
          size_t j = 0; for (; j < sizeof(k_sti); j++) if (t[p + j] != k_sti[j]) break;
          if (j == sizeof(k_sti)) { hit = p; n++; }
      }
      if (n == 1) { o->sti_rva = text_rva + (uint32_t)hit + STI_FB_OFF; o->sti_ok = 1; }
      else rc = -1;
    }
    for (i = 0; i < PS5_WL_SITES; i++) {
        size_t hit = 0, n = 0;
        for (size_t p = 0; p < len; p++) if (match_site(t, len, p, &k_sites[i])) { hit = p; n++; }
        if (n == 1) { o->site_rva[i] = text_rva + (uint32_t)hit; o->sites_ok++; }
        else if (rc == 0) rc = -(2 + i);
    }
    return rc;
}
