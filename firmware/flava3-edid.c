int ps5_flava3_edid_stage(unsigned stage, struct ps5_hdmi_commands *out) {
    struct ps5_hdmi_commands p;
    if (!out || stage >= PS5_FLAVA3_EDID_STAGES) return -1;
    if (ps5_hdmi_commands_init(&p, stage >= 6 ? 4 : 0)) return -1;   /* i2c_init(0) / i2c_init(4) */
    if (stage == 0) {
        if (ps5_hdmi_commands_table(&p, k_table_4_2, sizeof(k_table_4_2) / 4)) return -1;
    } else if (stage <= 4) {
        if (ps5_hdmi_commands_sequence(&p, k_edid_seq[stage - 1], sizeof(k_edid_seq[0]))) return -1;
    } else if (stage == 5) {
        if (ps5_hdmi_commands_sequence(&p, k_wait_pll, sizeof(k_wait_pll))) return -1;
    } else if (stage == 6) {                                           /* unk_akv */
        static const uint8_t v7006 = 0x12, v7a88 = 0xff;
        struct ps5_hdmi_register_write w[2] = {{0x7006, &v7006, 1}, {0x7a88, &v7a88, 1}};
        static const uint8_t v7a8b = 0x05, v7a89 = 0x01;
        struct ps5_hdmi_register_write w2[2] = {{0x7a8b, &v7a8b, 1}, {0x7a89, &v7a89, 1}};
        if (ps5_hdmi_commands_write_block(&p, w, 2) ||
            ps5_hdmi_commands_wait(&p, 0x7a84, 0x01, 0) ||
            ps5_hdmi_commands_write_single(&p, 0x7a83, 0x88) ||     /* i2c_cmd_2_1 = write_single wire format */
            ps5_hdmi_commands_wait(&p, 0x7a84, 0xa0, 1) ||
            ps5_hdmi_commands_wait(&p, 0x7a84, 0x01, 0) ||
            ps5_hdmi_commands_write_block(&p, w2, 2) ||
            ps5_hdmi_commands_delay(&p, 20) ||
            ps5_hdmi_commands_write_single(&p, 0x7a83, 0x0e) ||
            ps5_hdmi_commands_wait(&p, 0x7a84, 0xa0, 1)) return -1;
    } else {                                                           /* sceControlHdmiEvent(1) */
        if (ps5_hdmi_commands_event(&p, 4, 1)) return -1;
    }
    *out = p;
    return 0;
}
int ps5_flava3_edid_request(const struct ps5_icc_io *io, unsigned *completed,
                            ps5_icc_notification callback, void *context) {
    if (completed) *completed = 0;
    if (!io) return -1;
    for (unsigned s = 0; s < PS5_FLAVA3_EDID_STAGES; s++) {
        struct ps5_hdmi_commands p;
        int r = ps5_flava3_edid_stage(s, &p);
        if (!r) r = ps5_hdmi_commands_submit(io, &p, callback, context);
        if (r) return r;
        if (completed) *completed = s + 1;
    }
    return 0;
}
